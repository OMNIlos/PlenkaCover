function sourceLabel(source: string) {
  if (source === '1C' || source === 'mock') return 'учётный снимок';
  if (source === 'warehouse_fact') return 'факт склада';
  if (source === 'manual_platform') return 'ручной учет';
  return 'данные';
}

function movementStatusLabel(status: string) {
  if (status === 'requires_second_signature') return 'Ждет второй подписи';
  if (status === 'signed') return 'Подписано';
  if (status === 'rejected') return 'Отклонено';
  return 'Черновик перемещения';
}

