import type { DomainEventName, Role, RoleInboxCtaKind, RoleInboxSeverity } from '@plenka/contracts';

export type RoleInboxPresentation = {
  eventType: DomainEventName;
  recipientRole: Role;
  nextOwnerRole: Role;
  severity: RoleInboxSeverity;
  title: string;
  body: string;
  cta: {
    kind: RoleInboxCtaKind;
    section: string;
  };
};

const RELATED_ROLE_ROUTES: Record<
  Exclude<Role, 'admin'>,
  { kind: RoleInboxCtaKind; section: string }
> = {
  commercial: { kind: 'commercial_order', section: 'В работе' },
  production_lead: { kind: 'production_order', section: 'Проблемы' },
  operator: { kind: 'operator_roll', section: 'Рулоны и заказы' },
  warehouse: { kind: 'warehouse_intake', section: 'Приемка' },
  finance: { kind: 'finance_order', section: 'Обзор' },
  director: { kind: 'director_decision', section: 'Требуют решения' },
};

function relatedAlert(
  eventType: DomainEventName,
  recipientRole: Exclude<Role, 'admin'>,
  severity: RoleInboxSeverity,
  title: string,
  body: string,
  cta = RELATED_ROLE_ROUTES[recipientRole],
): RoleInboxPresentation {
  return {
    eventType,
    recipientRole,
    nextOwnerRole: recipientRole,
    severity,
    title,
    body,
    cta,
  };
}

