const routeKey = (eventType: string, recipientRole: Role) => `${eventType}\u0000${recipientRole}`;

const presentationsByRoute: ReadonlyMap<string, RoleInboxPresentation> = new Map(
  ROLE_INBOX_PRESENTATIONS.map((presentation) => [
    routeKey(presentation.eventType, presentation.recipientRole),
    presentation,
  ]),
);

export function presentationFor(
  eventType: string,
  recipientRole: Role,
): RoleInboxPresentation | undefined {
  return presentationsByRoute.get(routeKey(eventType, recipientRole));
}

export function recipientsFor(eventType: string): Role[] {
  return ROLE_INBOX_PRESENTATIONS.filter(
    (presentation) => presentation.eventType === eventType,
  ).map((presentation) => presentation.recipientRole);
}

export function eventTypesFor(recipientRole: Role): DomainEventName[] {
  return ROLE_INBOX_PRESENTATIONS.filter(
    (presentation) => presentation.recipientRole === recipientRole,
  ).map((presentation) => presentation.eventType);
}
